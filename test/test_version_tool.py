"""Exercise release-version generation using disposable repository roots."""

import contextlib
import importlib.util
import io
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest
from unittest import mock


SPEC = importlib.util.spec_from_file_location(
    "generate_version", Path(__file__).resolve().parents[1] / "scripts/generate_version.py"
)
VERSION_TOOL = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(VERSION_TOOL)


class VersionToolTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.header = self.root / "include/DP8382x/Version.h"
        self.metadata = {
            "name": "DP8382x",
            "version": "0.1.0",
            "description": "Portable PHY driver.",
            "license": "MIT",
            "repository": "https://example.invalid/DP8382x.git",
        }
        self.write_metadata(self.metadata)

    def write_metadata(self, metadata):
        (self.root / "library.json").write_text(json.dumps(metadata), encoding="utf-8")

    def run_tool(self, command):
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            return VERSION_TOOL.run(command, self.root)

    def seed_header(self):
        self.assertEqual(self.run_tool("sync"), 0)
        return self.header.read_bytes()

    def test_valid_boundary_versions(self):
        for version, numbers in (
            ("0.0.0", (0, 0, 0)),
            ("65535.65535.65535", (65535, 65535, 65535)),
            ("1.20.300", (1, 20, 300)),
        ):
            with self.subTest(version=version):
                self.write_metadata(dict(self.metadata, version=version))
                self.assertEqual(
                    VERSION_TOOL.read_version(self.root / "library.json"),
                    (*numbers, version),
                )
                self.assertEqual(self.run_tool("sync"), 0)
                content = self.header.read_bytes()
                for label, number in zip(("MAJOR", "MINOR", "PATCH"), numbers):
                    self.assertIn(
                        f"inline constexpr std::uint16_t VERSION_{label} = {number};\n".encode(),
                        content,
                    )
                self.assertIn(f'inline constexpr char VERSION_STRING[] = "{version}";\n'.encode(), content)
                self.assertNotIn(b"\r", content)
                self.assertEqual(self.run_tool("check"), 0)

    def test_exact_header_bytes(self):
        expected = b'''/// @file Version.h
/// @brief Generated portable release-version values.
/// @details Generated by scripts/generate_version.py from library.json.
/// Do not edit this file. This version does not describe a flashed image or Git revision.
#pragma once

#include <cstdint>

/// @brief Portable DP8382x release metadata.
namespace DP8382x {
/// @brief Release major component, 0 through 65535.
inline constexpr std::uint16_t VERSION_MAJOR = 0;
/// @brief Release minor component, 0 through 65535.
inline constexpr std::uint16_t VERSION_MINOR = 1;
/// @brief Release patch component, 0 through 65535.
inline constexpr std::uint16_t VERSION_PATCH = 0;
/// @brief Release semantic version, without firmware Git or build identity.
inline constexpr char VERSION_STRING[] = "0.1.0";
} // namespace DP8382x
'''
        self.assertEqual(self.seed_header(), expected)

    def test_invalid_versions_preserve_header(self):
        original = self.seed_header()
        for version in (
            "", "1.2", "1.2.3.4", "01.2.3", "1.02.3", "1.2.03",
            "-1.2.3", "+1.2.3", "1.2.3-alpha", "1.2.3+build", " 1.2.3",
            "1.2.3\n", "١.2.3", "65536.0.0", "0.65536.0", "0.0.65536",
            123, None, True, ["1.2.3"], {"value": "1.2.3"},
        ):
            for command in ("sync", "check"):
                with self.subTest(version=version, command=command):
                    self.write_metadata(dict(self.metadata, version=version))
                    with self.assertRaises(ValueError):
                        self.run_tool(command)
                    self.assertEqual(self.header.read_bytes(), original)

    def test_invalid_metadata_preserves_header(self):
        original = self.seed_header()
        cases = [[], None, dict(self.metadata, name="Other"), dict(self.metadata, extra="unknown")]
        for field in self.metadata:
            cases.append({key: value for key, value in self.metadata.items() if key != field})
            for value in ("", "   ", 42, False, None, [], {}):
                cases.append(dict(self.metadata, **{field: value}))
        for metadata in cases:
            for command in ("sync", "check"):
                with self.subTest(metadata=metadata, command=command):
                    self.write_metadata(metadata)
                    with self.assertRaises(ValueError):
                        self.run_tool(command)
                    self.assertEqual(self.header.read_bytes(), original)

    def test_bad_json_and_duplicate_keys_preserve_header(self):
        original = self.seed_header()
        valid = json.dumps(self.metadata)
        for payload in (
            b"{", b"\xff", b"[] trailing", b'{"version": NaN}',
            b'{"version": Infinity}', b'{"version": -Infinity}',
            (valid[:-1] + ', "version": "1.2.3"}').encode(),
            (valid[:-1] + ', "extra": {"x": 1, "x": 2}}').encode(),
        ):
            for command in ("sync", "check"):
                with self.subTest(payload=payload, command=command):
                    (self.root / "library.json").write_bytes(payload)
                    with self.assertRaises((ValueError, UnicodeError)):
                        self.run_tool(command)
                    self.assertEqual(self.header.read_bytes(), original)

    def test_check_missing_output_does_not_create_directories(self):
        self.assertEqual(self.run_tool("check"), 1)
        self.assertEqual(sorted(path.name for path in self.root.iterdir()), ["library.json"])

    def test_cli_returns_failure_without_changing_output(self):
        script = self.root / "scripts/generate_version.py"
        script.parent.mkdir()
        shutil.copyfile(VERSION_TOOL.__file__, script)

        def invoke(command):
            return subprocess.run([sys.executable, str(script), command], cwd=self.root,
                                  capture_output=True, text=True, check=False)

        self.assertEqual(invoke("check").returncode, 1)  # Missing header.
        self.assertEqual(invoke("sync").returncode, 0)
        original = self.header.read_bytes()
        self.write_metadata(dict(self.metadata, version="01.2.3"))
        self.assertEqual(invoke("check").returncode, 1)
        self.assertEqual(invoke("sync").returncode, 1)
        self.assertEqual(self.header.read_bytes(), original)

    def test_import_in_copied_repository_does_not_generate_output(self):
        script = self.root / "scripts/generate_version.py"
        script.parent.mkdir()
        script.write_bytes(Path(VERSION_TOOL.__file__).read_bytes())
        spec = importlib.util.spec_from_file_location("copied_version_tool", script)
        module = importlib.util.module_from_spec(spec)
        stdout, stderr = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
            spec.loader.exec_module(module)
        self.assertEqual(module.ROOT, self.root)
        self.assertEqual(stdout.getvalue(), "")
        self.assertEqual(stderr.getvalue(), "")
        self.assertFalse((self.root / "include").exists())

    def test_check_stale_output_never_writes(self):
        original = self.seed_header()
        for payload in (b"stale\n", original.replace(b"\n", b"\r\n"), b"\xff\xfe"):
            with self.subTest(payload=payload):
                self.header.write_bytes(payload)
                os.utime(self.header, ns=(1_000_000_000, 1_000_000_000))
                before = self.header.stat().st_mtime_ns
                with mock.patch.object(VERSION_TOOL.tempfile, "NamedTemporaryFile", side_effect=AssertionError("write attempted")):
                    self.assertEqual(self.run_tool("check"), 1)
                self.assertEqual(self.header.read_bytes(), payload)
                self.assertEqual(self.header.stat().st_mtime_ns, before)
                self.assertEqual(list(self.header.parent.glob(".Version.h.*.tmp")), [])
                self.assertEqual(self.run_tool("sync"), 0)
                self.assertEqual(self.header.read_bytes(), original)

    def test_repeated_sync_preserves_bytes_and_mtime(self):
        original = self.seed_header()
        os.utime(self.header, ns=(1_000_000_000, 1_000_000_000))
        before = self.header.stat().st_mtime_ns
        with mock.patch.object(VERSION_TOOL.tempfile, "NamedTemporaryFile", side_effect=AssertionError("unnecessary write")):
            for _ in range(3):
                self.assertEqual(self.run_tool("sync"), 0)
                self.assertEqual(self.run_tool("check"), 0)
        self.assertEqual(self.header.read_bytes(), original)
        self.assertEqual(self.header.stat().st_mtime_ns, before)

    def test_temp_creation_failure_preserves_old_header(self):
        original = self.seed_header()
        self.write_metadata(dict(self.metadata, version="1.2.3"))
        with mock.patch.object(VERSION_TOOL.tempfile, "NamedTemporaryFile", side_effect=OSError("injected create failure")):
            with self.assertRaisesRegex(OSError, "injected create failure"):
                self.run_tool("sync")
        self.assertEqual(self.header.read_bytes(), original)
        self.assertEqual(list(self.header.parent.glob(".Version.h.*.tmp")), [])

    def test_temp_write_failure_preserves_old_header_and_cleans_temp(self):
        original = self.seed_header()
        self.write_metadata(dict(self.metadata, version="1.2.3"))
        create_file = VERSION_TOOL.tempfile.NamedTemporaryFile
        observed = []

        @contextlib.contextmanager
        def failing_file(**kwargs):
            with create_file(**kwargs) as output:
                observed.append(Path(output.name))
                write = output.write

                def partial_write(data):
                    write(data[:10])
                    raise OSError("injected write failure")

                with mock.patch.object(output, "write", side_effect=partial_write):
                    yield output

        with mock.patch.object(VERSION_TOOL.tempfile, "NamedTemporaryFile", side_effect=failing_file):
            with self.assertRaisesRegex(OSError, "injected write failure"):
                self.run_tool("sync")
        self.assertEqual(len(observed), 1)
        self.assertFalse(observed[0].exists())
        self.assertEqual(self.header.read_bytes(), original)
        self.assertEqual(list(self.header.parent.glob(".Version.h.*.tmp")), [])

    def test_replace_failure_preserves_old_header_and_cleans_temp(self):
        original = self.seed_header()
        self.write_metadata(dict(self.metadata, version="1.2.3"))
        observed = []

        def fail_replace(source, destination):
            source = Path(source)
            observed.append(source)
            self.assertEqual(source.parent, self.header.parent)
            self.assertEqual(destination, self.header)
            self.assertTrue(source.is_file())
            self.assertIn(b'VERSION_STRING[] = "1.2.3";', source.read_bytes())
            self.assertEqual(self.header.read_bytes(), original)
            raise OSError("injected replace failure")

        with mock.patch.object(VERSION_TOOL.os, "replace", side_effect=fail_replace):
            with self.assertRaisesRegex(OSError, "injected replace failure"):
                self.run_tool("sync")
        self.assertEqual(len(observed), 1)
        self.assertFalse(observed[0].exists())
        self.assertEqual(self.header.read_bytes(), original)
        self.assertEqual(list(self.header.parent.glob(".Version.h.*.tmp")), [])


if __name__ == "__main__":
    unittest.main()
