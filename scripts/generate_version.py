#!/usr/bin/env python3
"""Generate the portable release-version header from library.json.

Usage: python scripts/generate_version.py sync|check

Version syntax is MAJOR.MINOR.PATCH, with ASCII decimal components 0..65535,
no leading zero except 0, and no prerelease/build suffix. The JSON root must
contain exactly name, version, description, license and repository. Duplicate
keys, wrong types and nonfinite JSON numbers are errors. The tool writes UTF-8
with LF line endings. Importing this module never changes the checkout.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
import re
import sys
import tempfile


ROOT = Path(__file__).resolve().parents[1]
HEADER = Path("include/DP8382x/Version.h")
FIELDS = ("name", "version", "description", "license", "repository")
VERSION_PATTERN = re.compile(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", re.ASCII)


def unique_object(pairs):
    """Reject duplicate JSON keys, including keys in nested objects."""
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate metadata key: {key}")
        result[key] = value
    return result


def reject_constant(value):
    """Reject JSON's nonstandard NaN and Infinity spellings."""
    raise ValueError(f"invalid JSON constant: {value}")


def read_version(path: Path) -> tuple[int, int, int, str]:
    """Validate metadata completely before any generated file is touched."""
    data = json.loads(path.read_bytes().decode("utf-8"),
                      object_pairs_hook=unique_object,
                      parse_constant=reject_constant)
    if not isinstance(data, dict) or set(data) != set(FIELDS):
        raise ValueError("library.json needs exactly name, version, description, license, repository")
    for field in FIELDS:
        if type(data[field]) is not str or not data[field].strip():
            raise ValueError(f"{field} must be a nonblank string")
    if data["name"] != "DP8382x":
        raise ValueError("name must be DP8382x")
    match = VERSION_PATTERN.fullmatch(data["version"])
    if match is None:
        raise ValueError("version must be MAJOR.MINOR.PATCH without suffix or leading zero")
    numbers = tuple(int(part) for part in match.groups())
    if any(part > 65535 for part in numbers):
        raise ValueError("version components must fit 0..65535")
    return *numbers, data["version"]


def render_header(version: tuple[int, int, int, str]) -> bytes:
    """Render only source-controlled release metadata, never Git/build identity."""
    major, minor, patch, text = version
    return f"""/// @file Version.h
/// @brief Generated portable release-version values.
/// @details Generated by scripts/generate_version.py from library.json.
/// Do not edit this file. This version does not describe a flashed image or Git revision.
#pragma once

#include <cstdint>

/// @brief Portable DP8382x release metadata.
namespace DP8382x {{
/// @brief Release major component, 0 through 65535.
inline constexpr std::uint16_t VERSION_MAJOR = {major};
/// @brief Release minor component, 0 through 65535.
inline constexpr std::uint16_t VERSION_MINOR = {minor};
/// @brief Release patch component, 0 through 65535.
inline constexpr std::uint16_t VERSION_PATCH = {patch};
/// @brief Release semantic version, without firmware Git or build identity.
inline constexpr char VERSION_STRING[] = "{text}";
}} // namespace DP8382x
""".encode("utf-8")


def run(command: str, root: Path = ROOT) -> int:
    """Check without writes or atomically replace one changed generated header."""
    if command not in {"sync", "check"}:
        raise ValueError("usage: generate_version.py sync|check")
    expected = render_header(read_version(root / "library.json"))
    destination = root / HEADER
    try:
        current = destination.read_bytes()
    except FileNotFoundError:
        current = None
    if command == "check":
        if current == expected:
            print(f"current: {HEADER.as_posix()}")
            return 0
        print(f"stale or missing: {HEADER.as_posix()}", file=sys.stderr)
        return 1
    if current == expected:
        print(f"unchanged: {HEADER.as_posix()}")
        return 0

    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="wb", dir=destination.parent,
                                         prefix=".Version.h.", suffix=".tmp",
                                         delete=False) as output:
            temporary = Path(output.name)
            if output.write(expected) != len(expected):
                raise OSError("short write while preparing Version.h")
            output.flush()
        os.replace(temporary, destination)
        temporary = None
    except OSError as failure:
        if temporary is not None:
            try:
                temporary.unlink(missing_ok=True)
            except OSError as cleanup:
                raise OSError(f"{failure}; temporary cleanup also failed: {cleanup}") from failure
        raise
    print(f"updated: {HEADER.as_posix()}")
    return 0


def main(argv: list[str] | None = None) -> int:
    """Return nonzero for invalid metadata, stale output or I/O failure."""
    arguments = sys.argv[1:] if argv is None else argv
    if len(arguments) != 1:
        print("usage: generate_version.py sync|check", file=sys.stderr)
        return 2
    try:
        return run(arguments[0])
    except (OSError, UnicodeError, json.JSONDecodeError, ValueError) as error:
        print(f"version generation failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
